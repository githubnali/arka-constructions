import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { extname, relative, resolve, sep } from "node:path";
import sharp from "sharp";

const publicRoot = resolve("public");
const imageRoot = resolve(publicRoot, "images");
const manifestPath = resolve("src/generated/imageManifest.ts");
const supportedExtensions = new Set([".jpg", ".jpeg", ".png"]);

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(entries.map((entry) => {
    const path = resolve(directory, entry.name);
    return entry.isDirectory() ? walk(path) : path;
  }));
  return files.flat();
}

function webPath(path) {
  return `/${relative(publicRoot, path).split(sep).join("/")}`;
}

function requestedWidths(source, width) {
  if (source.endsWith("/arka-logo.png")) return [64];
  if (/\/(hero-|service-(commercial|industrial|residential))/.test(source)) {
    return [768, 1600];
  }
  return [480, 960];
}

const allImageFiles = await walk(imageRoot);
await Promise.all(
  allImageFiles
    .filter((path) => /-\d+\.webp$/i.test(path))
    .map((path) => rm(path)),
);

const sources = allImageFiles
  .filter((path) => supportedExtensions.has(extname(path).toLowerCase()))
  .sort();
const manifest = {};

for (const path of sources) {
  const source = webPath(path);
  const metadata = await sharp(path).metadata();
  if (!metadata.width || !metadata.height) continue;

  const requested = requestedWidths(source, metadata.width);
  const widths = requested.filter((width) => width <= metadata.width);
  if (!widths.length || widths.at(-1) < Math.min(metadata.width, requested.at(-1))) {
    widths.push(Math.min(metadata.width, requested.at(-1)));
  }
  const extension = extname(path);
  const stem = path.slice(0, -extension.length);
  const variants = [];

  for (const width of widths) {
    const output = `${stem}-${width}.webp`;
    await sharp(path)
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: source.endsWith("/arka-logo.png") ? 86 : 78, effort: 5 })
      .toFile(output);
    variants.push({ src: webPath(output), width });
  }

  manifest[source] = {
    width: metadata.width,
    height: metadata.height,
    variants,
  };
}

await mkdir(resolve("src/generated"), { recursive: true });
await writeFile(
  manifestPath,
  `// Generated by scripts/optimize-images.mjs. Do not edit manually.\nexport const imageManifest = ${JSON.stringify(manifest, null, 2)} as const;\n`,
);

console.log(`Optimized ${sources.length} source images into responsive WebP variants.`);
